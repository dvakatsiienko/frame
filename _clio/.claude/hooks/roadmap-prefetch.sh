#!/bin/bash
# the linear initiative «roadmap» — the live step, its scope, the timeline, the mil tail in
# execution order. one query, ~25 lines, no due dates by design (dima, 2026-09-03).
INIT=70e6718f-fab6-4a1f-83b8-50bc659d706c
# --outline: four lines into memory/_roadmap.md, the resident outline every turn and every compaction reads (dima, 2026-10-10)
if [ "${1:-}" = --outline ]; then
  out="$HOME/frame/_clio/memory/_roadmap.md"
  body=$(linear api "query { initiative(id: \"$INIT\") { description content } projectMilestones(first: 50) { nodes { name project { name } issues(first: 50) { nodes { state { type } } } } } }" 2>/dev/null \
  | jq -r '
    .data as $d |
    ($d.initiative.description // "") as $desc |
    "# roadmap outline — generated by roadmap-prefetch.sh --outline at every boot and compaction, never edit",
    "",
    "- order: " + ([$d.initiative.content | split("\n")[] | select(test("^[0-9]+\\. ")) | sub("^[0-9]+\\. "; "") | (split(" — ")[0]) + (if test("\\(done [0-9]") then " ✅" else "" end)] | join(" → ")),
    "- now: " + (($desc | capture("now: (?<n>[^.]*)").n) // "?"),
    "- next: " + (($desc | capture("next: (?<n>[^.]*)").n) // "?"),
    "- started mils: " + ([$d.projectMilestones.nodes[] | ([.issues.nodes[] | select(.state.type == "completed" or .state.type == "canceled")] | length) as $done | (.issues.nodes | length) as $all | select($done > 0 and $done < $all) | "\(.project.name) · \(.name) \($done)/\($all)"] | join(", ") | if . == "" then "none" else . end)
  ') || exit 0
  [ -n "$body" ] && printf '%s\n' "$body" > "$out" && sed -n '3,$p' "$out"
  exit 0
fi
linear api "query { initiative(id: \"$INIT\") { name status description content projects(first: 20) { pageInfo { hasNextPage } nodes { name status { name } startDate issues(first: 50, filter: {state: {type: {nin: [\"completed\", \"canceled\"]}}, projectMilestone: {null: true}}) { pageInfo { hasNextPage } nodes { identifier } } } } } projectRelations(first: 30) { nodes { type project { name } relatedProject { name } anchorType relatedAnchorType } } projectMilestones(first: 50) { pageInfo { hasNextPage } nodes { name status project { name } issues(first: 50) { nodes { identifier sortOrder state { type } } } } } }" 2>/dev/null \
| jq -r '
  .data as $d |
  "-- the roadmap board: copy it as is into the opening reply, drift line as fixed (dima, 2026-10-25) --",
  ([$d.initiative.content | split("\n")[] | select(test("^[0-9]+\\. "))
    | {n: capture("^(?<n>[0-9]+)\\. ").n, p: (sub("^[0-9]+\\. "; "") | split(" — ")[0]), what: (sub("^[0-9]+\\. "; "") | split(" — ")[1] // "" | gsub(" ?\\((\\[[^]]+\\]\\([^)]+\\)(, )?)+\\)"; "") | gsub("\\[(?<t>[^]]+)\\]\\([^)]+\\)"; "\\(.t)")), done: test("\\(done [0-9]")}
    | select(.done | not)]) as $steps |
  ([($d.initiative.content | split("## the milestone queue")[1] // "" | split("\n## ")[0] // "" | split("\n")[])
    | select(startswith("* ") and contains(" · ")) | sub("^\\* "; "") | split(" · ")
    | {name: (.[:-1] | join(" · ")), project: .[-1]}]) as $queue |
  [$queue[] as $q | $d.projectMilestones.nodes[] | select(.name == $q.name and .project.name == $q.project)] as $matched |
  ($matched | map(select(.status != "done"))) as $live |
  ([$queue[] | . as $q | select([$d.projectMilestones.nodes[] | select(.name == $q.name and .project.name == $q.project)] | length == 0) | "\(.name) · \(.project)"]) as $ghosts |
  ([$d.projectMilestones.nodes[] | select(.status != "done") | . as $m | select([$queue[] | select(.name == $m.name and .project == $m.project.name)] | length == 0) | "\(.name) · \(.project.name)"]) as $unqueued |
  ([(if ($live[0].project.name // "") as $top | ([$steps[0].p, "cli"] | index($top)) == null then "the queue top (\($live[0].name // "none")) is off the now step and the cli track" else empty end),
    (if ($unqueued | length) > 0 then "open milestones missing from the queue: \($unqueued | join(", "))" else empty end),
    (if ($ghosts | length) > 0 then "queue lines matching no milestone: \($ghosts | join(", "))" else empty end)]) as $issues |
  ([$live[:7][].project.name] | unique) as $hot |
  ([$live[].project.name] | unique) as $queued |
  ([$d.initiative.projects.nodes[] | .name as $p
    | (if ($hot | index($p)) != null then "In Progress" elif ($queued | index($p)) != null then "Planned" else "Backlog" end) as $want
    | select(.status.name != $want) | "\($p) \(.status.name) → \($want)"]) as $drift |
  "### 🧭 roadmap",
  (if ($issues | length) == 0 then "✅ health on track" else "⚠️ health at risk — \($issues | join("; "))" end),
  "🌔 now: step \($steps[0].n // "?"), \($steps[0].p // "?")\(if ($steps[0].what // "") != "" then " (\($steps[0].what))" else "" end); next: \($steps[1:4] | map(.p) | join(" → "))",
  "",
  "**milestone queue**:",
  "",
  ($live[:7] | to_entries[] | .value as $m
    | "\([$m.issues.nodes[] | select(.state.type == "completed" or .state.type == "canceled")] | length)/\($m.issues.nodes | length)" as $count
    | "\(.key + 1). \($m.name) \($count)"),
  "",
  (if ($drift | length) > 0 then "🧾 status drift, fix it this turn: \($drift | join(" · "))" else empty end),
  "-- roadmap initiative (\($d.initiative.status)) --",
  $d.initiative.description,
  ($d.initiative.content // "" | split("\n") | map(select(test("^[0-9]\\."))) | join("\n")),
  "-- scope: projects on the initiative, by start date --",
  ($d.initiative.projects.nodes | sort_by(.startDate // "9999") | map("\(.name) · \(.status.name) · \(.startDate // "undated")") | join("\n")),
  "-- dependencies --",
  ($d.projectRelations.nodes | map("\(.project.name) \(.anchorType) → \(.relatedProject.name) \(.relatedAnchorType)") | join("\n") | if . == "" then "none" else . end),
  "-- open milestones, tickets in execution order (sortOrder) --",
  ($d.projectMilestones.nodes
    | map(select([.issues.nodes[] | select(.state.type != "completed" and .state.type != "canceled")] | length > 0))
    | map("\(.project.name) · \(.name) · \([.issues.nodes[] | select(.state.type == "completed" or .state.type == "canceled")] | length)/\(.issues.nodes | length) · " + ([.issues.nodes[] | select(.state.type != "completed" and .state.type != "canceled")] | sort_by(.sortOrder) | map(.identifier) | join(" → ")))
    | join("\n")),
  "-- milestone health --",
  ([(if $d.initiative.projects.pageInfo.hasNextPage then "🟡 initiative: projects capped at 20, health incomplete" else empty end),
    (if $d.projectMilestones.pageInfo.hasNextPage then "🟡 milestones capped at 50, health incomplete" else empty end),
    ($d.initiative.projects.nodes[] | .name as $p
      | [$d.projectMilestones.nodes[] | select(.project.name == $p)] as $ms
      | (if .issues.pageInfo.hasNextPage then "🟡 \($p): unassigned issues capped at 50, health incomplete" else empty end),
        ($ms[] | select(.issues.nodes | length == 0) | "🟡 \($p) · \(.name): empty — fill it, or ask dima to delete it"),
        ($ms[] | select(.status != "done") | select(.name | test("lane [0-9]|(^|\\s)m[0-9]+( |$)|step [0-9]")) | "🟡 \($p) · \(.name): a number for a name — rename it to the outcome (cclio:pm)"),
        (if ($ms | length) > 0 and (.issues.nodes | length) > 0 then "🟡 \($p): \(.issues.nodes | length) open ticket(s) with no milestone — \([.issues.nodes[].identifier] | join(", "))" else empty end),
        ([$ms[] | select(.status != "done")] | length | select(. > 5) | "🟡 \($p): \(.) open milestones (aim for 4, 5 is fine)"))
  ] | if length == 0 then "🟢 milestones healthy" else .[] end)
' || echo "roadmap prefetch: linear unreachable"
